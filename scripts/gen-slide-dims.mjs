// Reads the intrinsic width/height of every project deck slide and writes
// src/data/slide-dims.ts. SlideGallery uses this to set width/height on
// each <img>, so the browser reserves the correct space before a heavy
// slide loads instead of the page jumping as images arrive.
//
// Run this after adding or replacing slides:
//   node scripts/gen-slide-dims.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const SLIDES_ROOT = 'public/projects'
const OUT = 'src/data/slide-dims.ts'

function webpSize(path) {
  const buf = readFileSync(path)
  const fmt = buf.toString('ascii', 12, 16)
  if (fmt === 'VP8 ') {
    return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff]
  }
  if (fmt === 'VP8L') {
    const b = buf.readUInt32LE(21)
    return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1]
  }
  if (fmt === 'VP8X') {
    return [buf.readUIntLE(24, 3) + 1, buf.readUIntLE(27, 3) + 1]
  }
  throw new Error(`Unrecognised WebP chunk in ${path}`)
}

const dims = {}

for (const slug of readdirSync(SLIDES_ROOT, { withFileTypes: true })) {
  if (!slug.isDirectory()) continue
  const slidesDir = join(SLIDES_ROOT, slug.name, 'slides')
  if (!existsSync(slidesDir)) continue

  const files = readdirSync(slidesDir).filter((f) => f.endsWith('.webp')).sort()
  if (!files.length) continue

  dims[slug.name] = files.map((f) => webpSize(join(slidesDir, f)))
}

const banner =
  '// Generated by scripts/gen-slide-dims.mjs. Do not hand-edit.\n' +
  '// Re-run after adding or replacing slides in public/projects/<slug>/slides.\n\n'
writeFileSync(
  OUT,
  `${banner}export const slideDims: Record<string, [number, number][]> = ${JSON.stringify(dims, null, 2)}\n`,
)
console.log(`Wrote ${OUT}: ${Object.keys(dims).length} deck(s).`)
